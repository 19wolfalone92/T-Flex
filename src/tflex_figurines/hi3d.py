"""Hi3D 3.0 official API client: AK/SK Basic auth -> short-lived Bearer token.

No generation requests are sent unless explicitly invoked by caller.
Documentation:
https://docs.hi3d.ai/en/api/api-reference/list/get-token
https://docs.hi3d.ai/en/api/api-reference/list/create-task
"""
from __future__ import annotations

import os
import re
import time
from contextlib import ExitStack
from pathlib import Path

import requests

from .source_images import validate_generation_image
from .tripo import TripoError, valid_download_url

ROOT = "https://api.hitem3d.ai/open-api/v1"
MAX_IMAGE = 20_000_000
MAX_GLb = 200 * 1024 * 1024
VIEWS = ("front", "back", "left", "right")
TASK_ID = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,240}$")
PROFILES = {
    # Print/slicer: real geometry, not texture detail. Conservative first trial.
    "quality": {"resolution": "2048quality", "face": "2000000"},
    # Maximum official v3.0 geometry: slower and potentially dearer.
    "master": {"resolution": "2048master", "face": "5000000"},
}
FINISHED_ERROR = {"failed", "cancelled", "expired"}


class Hi3DError(TripoError):
    """Sanitized Hi3D errors, without access tokens or signed URLs."""


class Hi3DClient:
    def __init__(
        self,
        access_key: str | None = None,
        secret_key: str | None = None,
        session: requests.Session | None = None,
    ):
        access = access_key if access_key is not None else os.environ.get("HI3D_ACCESS_KEY", "")
        secret = secret_key if secret_key is not None else os.environ.get("HI3D_SECRET_KEY", "")
        if not isinstance(access, str) or not access.strip():
            raise Hi3DError("HI3D_ACCESS_KEY is missing")
        if not isinstance(secret, str) or not secret.strip():
            raise Hi3DError("HI3D_SECRET_KEY is missing")
        self._access = access.strip()
        self._secret = secret.strip()
        self._bearer: str | None = None
        self.session = session or requests.Session()

    def _call(self, method: str, path: str, **kwargs) -> dict:
        headers = {"Accept": "application/json"}
        if path == "/auth/token":
            # Basic is generated by requests, never interpolated into logs.
            kwargs["auth"] = (self._access, self._secret)
        else:
            if not self._bearer:
                self.authenticate()
            # Vendor docs use "Token" for split/query-task, "Bearer" otherwise.
            scheme = "Token" if path == "/split/query-task" else "Bearer"
            headers["Authorization"] = scheme + " " + self._bearer
        try:
            res = self.session.request(
                method, ROOT + path, headers=headers, timeout=30,
                allow_redirects=False, **kwargs
            )
        except requests.RequestException as exc:
            raise Hi3DError("Hi3D network or timeout failure") from exc
        if not 200 <= res.status_code < 300:
            raise Hi3DError(f"Hi3D returned HTTP {res.status_code}")
        try:
            payload = res.json()
        except ValueError as exc:
            raise Hi3DError("Hi3D returned invalid JSON") from exc
        if not isinstance(payload, dict) or payload.get("code") not in (200, "200"):
            code = payload.get("code") if isinstance(payload, dict) else None
            # Don't echo the API message (may include user-provided content).
            raise Hi3DError(f"Hi3D rejected request (code {str(code)[:24]})")
        data = payload.get("data")
        if not isinstance(data, dict):
            raise Hi3DError("Hi3D response missing data object")
        return data

    def authenticate(self) -> None:
        data = self._call("POST", "/auth/token", json={})
        token = data.get("accessToken")
        if not isinstance(token, str) or len(token) < 12:
            raise Hi3DError("Hi3D returned no valid accessToken")
        self._bearer = token

    def balance(self) -> dict:
        return self._call("GET", "/balance")

    def submit(
        self,
        views: dict[str, Path],
        *,
        profile: str = "quality",
        geometry_only: bool = True,
    ) -> str:
        if profile not in PROFILES:
            raise ValueError(f"Unknown Hi3D profile; choose {sorted(PROFILES)}")
        if not 1 <= len(views) <= 4 or "front" not in views:
            raise ValueError("Hi3D needs a front image and at most 4 real views")
        if any(k not in VIEWS for k in views):
            raise ValueError("Use front/back/left/right image labels only")
        # Check EVERY image BEFORE network/authentication/cost.
        mime = {
            label: validate_generation_image(path, max_bytes=MAX_IMAGE, allow_webp=True)
            for label, path in views.items()
        }
        data = {
            "request_type": "1" if geometry_only else "3",
            "model": "hi3dv3.0",
            **PROFILES[profile],
            "rmbg": "1",
            "format": "2",  # GLB for downstream pipeline
        }
        if not geometry_only:
            # PBR is documented only for request_type 2/3.
            data["pbr"] = "1"
        with ExitStack() as stack:
            if len(views) == 1:
                path = views["front"]
                files = [("images", (path.name, stack.enter_context(path.open("rb")), mime["front"]))]
            else:
                files = []
                for label in VIEWS:
                    if label in views:
                        path = views[label]
                        files.append(("multi_images", (path.name, stack.enter_context(path.open("rb")), mime[label])))
                data["multi_images_bit"] = "".join("1" if label in views else "0" for label in VIEWS)
            # A failed/uncertain submit must NEVER be automatically retried.
            result = self._call("POST", "/submit-task", data=data, files=files)
        task_id = result.get("task_id")
        if not isinstance(task_id, str) or not TASK_ID.fullmatch(task_id):
            raise Hi3DError("Hi3D did not return a valid task ID")
        return task_id

    def submit_split(
        self,
        mesh: Path,
        *,
        kind: str = "character",
        template: str = "a",
        joint: str = "pin",
        merge: bool = True,
        level: str = "medium",
    ) -> str:
        """Submit vendor's billable 3D split-to-print task (2..6 parts).

        Character templates a/b/c/d/e/f: 6/5/4/4/3/2 parts.
        This can preserve semantic part boundaries unlike a planar cut.
        """
        if kind not in ("character", "general"):
            raise ValueError("Split mode must be character or general")
        if kind == "character":
            if template not in ("a", "b", "c", "d", "e", "f"):
                raise ValueError("Character split template must be a..f")
            if joint not in ("none", "ball", "dovetail", "pin"):
                raise ValueError("Invalid connector")
        elif level not in ("low", "medium", "high"):
            raise ValueError("General split level must be low/medium/high")
        ext = mesh.suffix.lower()
        if ext not in (".glb", ".stl", ".obj") or not mesh.is_file():
            raise ValueError("Existing GLB/STL/OBJ required for vendor split")
        if not 0 < mesh.stat().st_size <= 200_000_000:
            raise ValueError("Vendor split source must be 1 byte..200 MB")
        mime = {".glb": "model/gltf-binary", ".stl": "model/stl", ".obj": "text/plain"}[ext]
        payload = {"model": kind, "format": "2"}
        if kind == "character":
            payload.update({"part": template, "joint": joint})
            if joint != "none":
                payload["merge"] = "yes" if merge else "no"
        else:
            payload["level"] = level
        # Never repeat an uncertain POST: duplicate paid tasks are possible.
        with mesh.open("rb") as handle:
            result = self._call(
                "POST", "/split/create-task",
                data=payload, files={"mesh": (mesh.name, handle, mime)}
            )
        task_id = result.get("task_id")
        if not isinstance(task_id, str) or not TASK_ID.fullmatch(task_id):
            raise Hi3DError("Hi3D split request returned invalid task ID")
        return task_id

    def split_task(self, task_id: str) -> dict:
        if not isinstance(task_id, str) or not TASK_ID.fullmatch(task_id):
            raise ValueError("Invalid split task ID")
        return self._call("GET", "/split/query-task", params={"task_id": task_id})

    def wait_split(self, task_id: str, timeout: float = 1800, interval: float = 10) -> dict:
        if timeout <= 0 or interval <= 0:
            raise ValueError("Timeout and interval must be positive")
        deadline = time.monotonic() + timeout
        while True:
            data = self.split_task(task_id)
            state = data.get("state")
            if state == "success":
                return data
            if state in FINISHED_ERROR:
                raise Hi3DError(f"Hi3D split task ended {state}")
            if time.monotonic() >= deadline:
                raise Hi3DError("Split wait expired; use existing task ID, never re-submit")
            time.sleep(min(interval, max(0.01, deadline-time.monotonic())))

    def download_split(self, task_id: str, dest: Path) -> Path:
        return self._download_result(self.split_task(task_id), dest)

    def task(self, task_id: str) -> dict:
        if not isinstance(task_id, str) or not TASK_ID.fullmatch(task_id):
            raise ValueError("Invalid Hi3D task ID")
        return self._call("GET", "/query-task", params={"task_id": task_id})

    def wait(self, task_id: str, timeout: float = 1800, interval: float = 10) -> dict:
        if timeout <= 0 or interval <= 0:
            raise ValueError("Timeout and interval must be positive")
        deadline = time.monotonic() + timeout
        while True:
            task = self.task(task_id)
            state = task.get("state")
            if state == "success":
                return task
            if state in FINISHED_ERROR:
                raise Hi3DError(f"Hi3D task ended: {state}")
            if time.monotonic() >= deadline:
                raise Hi3DError("Wait timed out: retain task ID and resume, do not resubmit")
            time.sleep(min(interval, max(0.01, deadline - time.monotonic())))

    def download(self, task_id: str, dest: Path) -> Path:
        return self._download_result(self.task(task_id), dest)

    def _download_result(self, result: dict, dest: Path) -> Path:
        if result.get("state") != "success":
            raise Hi3DError("Hi3D task is not finished")
        url = result.get("url")
        if not isinstance(url, str):
            raise Hi3DError("Hi3D task returned no download URL")
        valid_download_url(url)
        if dest.suffix.lower() != ".glb" or dest.exists():
            raise ValueError("Output must be a new .glb file")
        dest.parent.mkdir(parents=True, exist_ok=True)
        tmp = dest.with_suffix(".glb.part")
        if tmp.exists():
            raise ValueError("Previous partial file exists")
        try:
            try:
                resp = self.session.get(url, timeout=60, stream=True, allow_redirects=False)
            except requests.RequestException as exc:
                raise Hi3DError("Hi3D GLB download network error") from exc
            with resp:
                if not 200 <= resp.status_code < 300:
                    raise Hi3DError(f"Hi3D model download HTTP {resp.status_code}")
                total = 0
                head = b""
                with tmp.open("xb") as f:
                    for chunk in resp.iter_content(chunk_size=65536):
                        if not chunk:
                            continue
                        total += len(chunk)
                        if total > MAX_GLb:
                            raise Hi3DError("Hi3D GLB size exceeds 200 MiB")
                        if len(head) < 4:
                            head += chunk[:4-len(head)]
                        f.write(chunk)
                    if head != b"glTF":
                        raise Hi3DError("Hi3D output is not GLB geometry")
            tmp.replace(dest)
            return dest
        finally:
            if tmp.exists():
                tmp.unlink()
